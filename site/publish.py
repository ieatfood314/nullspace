#!/usr/bin/env python3
"""Builds the Lakebed capsule for nullspace.lakebed.app from this folder, and deploys it.

    python3 site/publish.py            build ~/lakebed-apps/nullspace and deploy
    python3 site/publish.py --no-deploy   build only

Lakebed hosts a client app, not loose files, so index.html's body and style.css (with the font inlined)
are embedded in client/site.ts, the same way the apogee site does it.
"""
import base64, json, os, re, subprocess, sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
CAPSULE = Path(os.environ.get("NULLSPACE_CAPSULE", Path.home() / "lakebed-apps" / "nullspace"))
NODE_BIN = Path.home() / ".local/share/node22/bin"

html = (HERE / "index.html").read_text()
body = re.search(r"<body>(.*)</body>", html, re.S).group(1).strip()
title = re.search(r"<title>(.*?)</title>", html).group(1)
metas = dict(re.findall(r'<meta name="(description|theme-color)" content="([^"]*)"', html))
css = (HERE / "style.css").read_text()
font = base64.b64encode((HERE / "fonts/inter.woff2").read_bytes()).decode()
css = css.replace("url(fonts/inter.woff2)", f"url(data:font/woff2;base64,{font})")

(CAPSULE / "client").mkdir(parents=True, exist_ok=True)
(CAPSULE / "server").mkdir(exist_ok=True)
(CAPSULE / "client/site.ts").write_text(
    "// Generated by site/publish.py in the nullspace repo. Change the site there.\n"
    f"export const TITLE = {json.dumps(title)};\n"
    f"export const DESCRIPTION = {json.dumps(metas['description'])};\n"
    f"export const BODY = {json.dumps(body)};\n"
    f"export const CSS = {json.dumps(css)};\n"
)
(CAPSULE / "client/index.tsx").write_text('''import { useLayoutEffect } from "preact/hooks";
import { BODY, CSS, DESCRIPTION, TITLE } from "./site";

const HTML = { __html: BODY };

function meta(name: string, content: string) {
  const tag = document.querySelector<HTMLMetaElement>(`meta[name="${name}"]`) ?? document.head.appendChild(document.createElement("meta"));
  tag.name = name;
  tag.content = content;
}

export function App() {
  useLayoutEffect(() => {
    // Lakebed adds Tailwind to every page; its reset and utilities would fight the site's own CSS.
    for (const tag of document.querySelectorAll("style")) {
      if (tag.textContent?.includes("tailwindcss")) tag.remove();
    }
    const style = document.createElement("style");
    style.textContent = CSS;
    document.head.appendChild(style);
    document.title = TITLE;
    meta("description", DESCRIPTION);
    meta("viewport", "width=device-width, initial-scale=1, viewport-fit=cover");
    meta("theme-color", "#000000");
  }, []);

  return <div dangerouslySetInnerHTML={HTML} />;
}
''')
(CAPSULE / "server/index.ts").write_text('''import { capsule } from "lakebed/server";

export default capsule({
  name: "Nullspace",
  auth: { requireSignIn: false }
});
''')
(CAPSULE / "favicon.svg").write_text((HERE / "favicon.svg").read_text())
(CAPSULE / ".gitignore").write_text(".lakebed/\n.env.lakebed.server\n")
if not (CAPSULE / "README.md").exists():
    (CAPSULE / "README.md").write_text("Generated from `site/` in the nullspace repo by `site/publish.py`. Change the site there.\n")

print(f"capsule built in {CAPSULE}")
if "--no-deploy" not in sys.argv:
    env = {**os.environ, "PATH": f"{NODE_BIN}:{os.environ['PATH']}"}
    subprocess.run(["npx", "lakebed", "deploy"], cwd=CAPSULE, env=env, check=True)
